#!/usr/bin/env python3
"""Compile all 34 templates, run ATS + originality checks, output a markdown matrix."""
import json
import subprocess
import sys
import time
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "career-dashboard" / "api"))

import latex as latex_mod
import ats as ats_mod
import originality as originality_mod
from models import CareerDatabase

def main():
    db = CareerDatabase.model_validate_json((REPO / "career-dashboard" / "career_db.json").read_text())
    templates = latex_mod.registry(db)
    
    rows = []
    for t in templates:
        tid = t["id"]
        entry = {"id": tid, "name": t["name"], "pages": "?", "ats": "?", "grade": "?", "dup": "?", "cliches": "?", "ai": "?", "status": "ok"}
        try:
            r = latex_mod.compile_template(db, tid, force=True)
            entry["pages"] = r.get("pages", "?")
            if not r.get("ok"):
                entry["status"] = f"FAIL: {r.get('error','')[:60]}"
                rows.append(entry)
                continue
            # ATS
            a = ats_mod.check_with_cache(latex_mod.pdf_path(tid), db, tid.split("-")[0])
            entry["ats"] = a.get("score", "?")
            entry["grade"] = a.get("grade", "?")
            # Originality (best-effort)
            try:
                o = originality_mod.check_template(tid)
                entry["dup"] = o["duplication"]["score"]
                entry["cliches"] = o["cliches"]["count"]
                entry["ai"] = o["ai"]["band"]
            except Exception:
                entry["dup"] = entry["cliches"] = entry["ai"] = "n/a"
        except Exception as e:
            entry["status"] = f"ERROR: {e}"
        rows.append(entry)
        print(f"  {tid:<42} pages={entry['pages']} ats={entry['ats']} {entry['grade']} dup={entry['dup']} ai={entry['ai']}", flush=True)

    # Write markdown matrix
    lines = [
        f"# Compile-Verification Matrix — {date.today().isoformat()}",
        "",
        f"Generated by `scripts/verify_all.py`. {len(rows)} templates.",
        "",
        "| # | Template | Pages | ATS | Grade | Dup | Cliches | AI | Status |",
        "|---|----------|-------|-----|-------|-----|---------|----|--------|",
    ]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | `{r['id']}` | {r['pages']} | {r['ats']} | {r['grade']} | {r['dup']} | {r['cliches']} | {r['ai']} | {r['status']} |")
    
    ok = sum(1 for r in rows if r["status"] == "ok")
    lines += ["", f"**Summary:** {ok}/{len(rows)} compiled OK"]
    
    out = REPO / "docs" / "research" / f"matrix-{date.today().isoformat()}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"\nMatrix written to {out}")
    print(f"Compiled OK: {ok}/{len(rows)}")

if __name__ == "__main__":
    main()
